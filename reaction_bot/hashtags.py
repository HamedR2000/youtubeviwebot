"""هشتگ‌های پیش‌فرضی که به description هر آپلود اضافه می‌شن، مگر خودت
توی --description از قبل هشتگ گذاشته باشی. یوتیوب حداکثر ۱۵ تا هشتگ رو
قبول می‌کنه -- بیشتر از اون بشه، همه‌شون (نه فقط اضافه‌ها) نادیده گرفته
می‌شن، پس عمداً همینجا زیر اون سقف نگهش داشتیم."""

DEFAULT_HASHTAGS = (
    "#Shorts #ری_اکشن #طنز_ایرانی #خنده #خنده_دار #کلیپ_طنز "
    "#کمدی #طنز #ایرانی #فارسی #reaction #comedy"
)


def ensure_hashtags(description: str) -> str:
    """اگه description از قبل هیچ هشتگی نداشت، دسته‌ی پیش‌فرض رو ته‌ش
    اضافه می‌کنه. اگه خودت هشتگ گذاشته باشی، دست‌نخورده می‌مونه -- برای
    این‌که با هم جمع نشن و از ۱۵ تا رد نشیم."""
    if "#" in description:
        return description
    return (description + "\n\n" + DEFAULT_HASHTAGS).strip()
