"""عنوان‌های آماده و عمومی یوتیوب -- وقتی publish_ready.py یا main.py بدون
--title صدا زده بشن، از اینجا یکی انتخاب می‌شه. به‌ترتیب لیست پیش می‌ره
(نه کاملاً تصادفی) تا قبل از تکرار هر عنوان، همه‌ی بقیه هم یه‌بار
استفاده شده باشن -- بعد از هر دور، از اول شروع می‌شه.
"""
import json
import os

TITLES = [
    "این یکی رو از دست ندید 😂",
    "باورتون نمی‌شه چی دیدم!",
    "تا آخرش ببینید، حسابی می‌خندید",
    "ری‌اکشن نیما به این ویدیوی خنده‌دار",
    "وای این دیگه چی بود؟! 😂",
    "خنده‌ی امروز نیما اینجاست",
    "این ویدیو رو باید ببینید!",
    "نمی‌تونم جلوی خنده‌مو بگیرم 😆",
    "یکی از خنده‌دارترین چیزایی که دیدم",
    "این حرکتش دیوونه‌کننده‌ست!",
    "حاضرید بخندید؟ بزنید پلی",
    "امروز با این ویدیو حسابی خندیدم",
    "این صحنه رو باید صد بار ببینید",
    "خنده با نیما - یه قسمت جدید",
    "تا ته این ویدیو رو نگاه کنید 😂",
]

_STATE_PATH = os.path.join(os.path.dirname(__file__), ".title_cursor.json")


def pick_title() -> str:
    cursor = 0
    if os.path.exists(_STATE_PATH):
        with open(_STATE_PATH, encoding="utf-8") as f:
            cursor = json.load(f).get("cursor", 0)
    title = TITLES[cursor % len(TITLES)]
    with open(_STATE_PATH, "w", encoding="utf-8") as f:
        json.dump({"cursor": cursor + 1}, f)
    return title
